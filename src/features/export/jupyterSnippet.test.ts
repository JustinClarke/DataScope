import { describe, expect, it } from 'vitest';
import { buildJupyterSnippet } from './jupyterSnippet';
import type { TableRegistryEntry } from '../../types';

const sourceTable: TableRegistryEntry = {
  id: 't-1',
  tableName: 'orders',
  datasetId: 'ds-1',
  origin: 'file',
  rowCount: 100,
  columnCount: 5,
  memoryBytes: 4096,
  createdAt: '2026-07-20T00:00:00.000Z',
};

const derivedTable: TableRegistryEntry = {
  ...sourceTable,
  id: 't-2',
  tableName: 'orders_us',
  origin: 'derived',
  generatingSql: "CREATE TABLE orders_us AS\nSELECT * FROM orders WHERE country = 'US';",
};

describe('buildJupyterSnippet', () => {
  it('loads a source table with no generating-SQL comment', () => {
    const snippet = buildJupyterSnippet(sourceTable, 'parquet');
    expect(snippet).not.toContain('# Generated by:');
    expect(snippet).toContain('import pandas as pd');
    expect(snippet).toContain('df = pd.read_parquet("orders.parquet")');
  });

  it('includes the DuckDB alternative for a Parquet export', () => {
    const snippet = buildJupyterSnippet(sourceTable, 'parquet');
    expect(snippet).toContain('duckdb.read_parquet("orders.parquet").df()');
  });

  it('loads a CSV export via pd.read_csv, with no DuckDB alternative line', () => {
    const snippet = buildJupyterSnippet(sourceTable, 'csv');
    expect(snippet).toContain('df = pd.read_csv("orders.csv")');
    expect(snippet).not.toContain('duckdb.read_parquet');
  });

  it("carries a derived table's generating SQL as a leading comment, semicolon stripped", () => {
    const snippet = buildJupyterSnippet(derivedTable, 'parquet');
    const lines = snippet.split('\n');
    expect(lines[0]).toBe('# Generated by:');
    expect(lines[1]).toBe('# CREATE TABLE orders_us AS');
    expect(lines[2]).toBe("# SELECT * FROM orders WHERE country = 'US'");
    expect(snippet).toContain('df = pd.read_parquet("orders_us.parquet")');
  });
});
