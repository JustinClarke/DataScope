// Copy-to-Jupyter snippet (§12.2) — the zero-infrastructure handoff to the
// tool data people already trust. Paste-ready: a derived table's generating
// SQL travels along as a leading comment so the export is self-documenting
// once it's outside the app; a source table (no `generatingSql`) skips it.
import type { TableRegistryEntry } from "../../types";

function sqlComment(sql: string): string {
  return sql
    .trim()
    .replace(/;\s*$/, "")
    .split("\n")
    .map((line) => `# ${line}`)
    .join("\n");
}

export function buildJupyterSnippet(
  table: TableRegistryEntry,
  format: "parquet" | "csv",
): string {
  const filename = `${table.tableName}.${format}`;
  const provenance = table.generatingSql
    ? `# Generated by:\n${sqlComment(table.generatingSql)}\n\n`
    : "";
  const loadLine =
    format === "parquet"
      ? `df = pd.read_parquet("${filename}")\n# or, using DuckDB directly: duckdb.read_parquet("${filename}").df()`
      : `df = pd.read_csv("${filename}")`;

  return `${provenance}import pandas as pd\n\n${loadLine}\n`;
}
