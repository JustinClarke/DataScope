// "Copy for AI" context block (D31) — a compact, paste-into-a-chat description
// of a dataset's *shape*, never its rows. Zero raw cell values leave the
// browser: only the schema (tables, columns, inferred semantic + physical
// types), aggregate profile signals already surfaced elsewhere (null %,
// distinct count, detected keys), and the inferred relationships. When the join
// graph is cut, the relationships section is simply omitted — the block stays a
// valid schema summary. Deterministic and offline; produces plain Markdown.
import type { TableRegistryEntry } from "../types";
import type { FkEdge } from "./relationshipInference";

function columnLine(column: {
  name: string;
  semanticType: string;
  physicalType: string;
  nullPercentage: number | null;
  cardinality: number;
}): string {
  const parts = [
    `${column.semanticType.toLowerCase()} · ${column.physicalType}`,
  ];
  if (column.nullPercentage !== null && column.nullPercentage > 0) {
    parts.push(`${Math.round(column.nullPercentage)}% null`);
  }
  parts.push(`${column.cardinality.toLocaleString()} distinct`);
  return `  - \`${column.name}\` — ${parts.join(", ")}`;
}

/**
 * Build the Markdown context block. `edges` is passed only when the join graph
 * is enabled and has produced relationships; omit it (or pass an empty array)
 * for the schema-only cut path.
 */
export function buildAIContext(
  tables: TableRegistryEntry[],
  edges: FkEdge[] = [],
): string {
  const lines: string[] = [];
  lines.push("# Dataset structure (shape only — no data rows included)");
  lines.push("");

  for (const table of tables) {
    lines.push(
      `## ${table.tableName} — ${table.rowCount.toLocaleString()} rows × ${table.columnCount} columns`,
    );
    const columns = table.columns ?? [];
    if (columns.length === 0) {
      lines.push("  - (not yet profiled)");
    } else {
      for (const c of columns) lines.push(columnLine(c));
    }
    lines.push("");
  }

  if (edges.length > 0) {
    lines.push("## Inferred relationships (beta — confidence-labeled)");
    for (const edge of edges) {
      const tier = edge.confidence === "confident" ? "confident" : "candidate";
      lines.push(
        `  - \`${edge.childTable}.${edge.childColumn}\` → \`${edge.parentTable}.${edge.parentColumn}\` ` +
          `(${tier}, ${Math.round(edge.containment * 100)}% containment)`,
      );
    }
    lines.push("");
  }

  lines.push("_Generated by DataScope — structure only, nothing uploaded._");
  return lines.join("\n");
}
